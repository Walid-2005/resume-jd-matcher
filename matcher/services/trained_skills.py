def _apply_domain_filter(
    templates: "dict[str, list[str]]",
) -> "dict[str, list[str]]":
    cleaned: "dict[str, list[str]]" = {}
    for role, skills in templates.items():
        out: "list[str]" = []
        for skill in skills:
            sl = skill.lower()
            if sl in _DOMAIN_HR and role not in _HR_ALLOWED:
                continue
            if sl in _DOMAIN_MEDICAL and role not in _MEDICAL_ALLOWED:
                continue
            if sl in _DOMAIN_LEGAL and role not in _LEGAL_ALLOWED:
                continue
            out.append(skill)
        cleaned[role] = out
    return cleaned


